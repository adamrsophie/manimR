"""Generate R/tex_templates.R from manim's TexTemplateLibrary and
TexFontTemplates, so the preambles are copied exactly instead of retyped.

Run with a Python that has manim installed:

    python data-raw/tex_templates.py R/tex_templates.R
"""

import json
import sys
import unicodedata

from manim.utils.tex import TexTemplate
from manim.utils.tex_templates import TexFontTemplates, TexTemplateLibrary

DEFAULT = TexTemplate()
FIELDS = ["tex_compiler", "output_format", "documentclass", "placeholder_text", "post_doc_commands", "description"]


def raw(s):
    assert all(ord(c) < 128 for c in s), s
    assert ")---\"" not in s, s
    return 'r"---(' + s + ')---"'


def ascii_text(s):
    s = s.replace("ł", "l")
    return unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()


def specs(cls, var):
    names = [n for n in vars(cls) if not n.startswith("_")]
    lines = [f"{var} <- list("]
    for k, name in enumerate(names):
        t = getattr(cls, name)
        args = [f"preamble = {raw(t.preamble)}"]
        for f in FIELDS:
            v = getattr(t, f)
            if v != getattr(DEFAULT, f):
                args.append(f"{f} = " + (json.dumps(v) if f == "description" else raw(v)))
        sep = "," if k < len(names) - 1 else ""
        lines.append(f"  {name} = list(\n    " + ",\n    ".join(args) + f"\n  ){sep}")
    lines.append(")")
    return names, "\n".join(lines)


lib_names, lib_code = specs(TexTemplateLibrary, "tex_library_specs")
font_names, font_code = specs(TexFontTemplates, "tex_font_specs")
font_items = "\n".join(
    f"#' * `{n}`: {ascii_text(getattr(TexFontTemplates, n).description)}" for n in font_names
)

out = f"""# Generated by data-raw/tex_templates.py from manim.utils.tex_templates;
# rerun that script instead of editing the template specs by hand.

#' Libraries of LaTeX templates
#'
#' Ready made [TexTemplate()] objects, ported from manim's
#' `TexTemplateLibrary` and `TexFontTemplates`. Pass one as `tex_template` to
#' [Tex()] or [MathTex()], or make it the default with
#' `manim_config(tex_template = ...)`.
#'
#' Upstream exposes these as class attributes holding shared template
#' objects. A TexTemplate is a mutable R6 object here, so a shared one would
#' let `add_to_preamble()` on one use leak into every other use. Both
#' libraries are therefore functions returning a named list of fresh
#' templates on every call: write `TexTemplateLibrary()$ctex` where upstream
#' writes `TexTemplateLibrary.ctex`.
#'
#' `TexTemplateLibrary()` holds `default` and `threeb1b` (the 3b1b preamble),
#' `ctex` (the same with the `ctex` package, compiled with `xelatex`) and
#' `simple` (only the AMS packages).
#'
#' `TexFontTemplates()` holds font templates; many need extra LaTeX packages
#' or system fonts, and some need `xelatex` or `lualatex`. See
#' <http://jf.burnol.free.fr/showcase.html> for samples. The templates are:
#'
{font_items}
#'
#' @return A named list of [TexTemplate()] objects.
#' @export
#' @examples
#' names(TexTemplateLibrary())
#' tpl <- TexFontTemplates()$french_cursive
#' tpl$description
#' \\dontrun{{
#' MathTex("x^2 + y^2 = 1", tex_template = TexFontTemplates()$latin_modern_tw)
#' }}
TexTemplateLibrary <- function() tex_templates_from_specs(tex_library_specs)

#' @rdname TexTemplateLibrary
#' @export
TexFontTemplates <- function() tex_templates_from_specs(tex_font_specs)

tex_templates_from_specs <- function(specs) lapply(specs, function(s) do.call(TexTemplateClass$new, s))

{lib_code}

{font_code}
"""

with open(sys.argv[1], "w") as fh:
    fh.write(out)
