test_that("ManimColor matches upstream", {
  skip_if_not_installed("jsonlite")
  o <- jsonlite::fromJSON(test_path("fixtures", "manim_color_oracle.json"), simplifyVector = TRUE)
  c1 <- ManimColor("#FF8000")
  expect_equal(c1$to_integer(), o$to_integer)
  expect_equal(c1$to_int_rgb(), o$to_int_rgb)
  expect_equal(ManimColor("#FF800080")$to_hex(TRUE), o$to_hex_alpha)
  expect_equal(c1$to_hsv(), o$to_hsv)
  expect_equal(c1$to_hsl(), o$to_hsl)
  expect_equal(c1$invert()$to_rgba(), o$invert)
  expect_equal(c1$darker()$to_rgba(), o$darker)
  expect_equal(c1$lighter(0.5)$to_rgba(), o$lighter)
  expect_equal(c1$interpolate(ManimColor(BLUE), 0.3)$to_rgba(), o$interp)
  expect_equal(c1$contrasting()$to_hex(), o$contrast)
  expect_equal(ManimColor("#202020")$contrasting()$to_hex(), o$contrast_dark)
  expect_equal(c1$opacity(0.3)$to_rgba(), o$opacity)
  expect_equal((c1 + 0.1)$to_rgba(), o$add)
  expect_equal((c1 * ManimColor("#808080"))$to_rgba(), o$mul)
  expect_equal((c1 & ManimColor("#00FFFF"))$to_hex(), o$and)
  expect_equal(ManimColor(0x123456)$to_hex(), o$from_int)
  expect_equal(ManimColor(c(255L, 128L, 0L))$to_rgba(), o$from_ints)
  expect_equal(ManimColor(c(0.2, 0.4, 0.6))$to_rgba(), o$from_floats)
  expect_equal(ManimColorClass$from_hsv(c(0.5, 1, 1))$to_hex(), o$from_hsv)
  expect_equal(ManimColorClass$from_hsl(c(0.25, 1, 0.5))$to_hex(), o$from_hsl)
  expect_equal(ManimColor("blue_c")$to_hex(), o$name)
  expect_equal(ManimColor("#F80")$to_hex(), o$short_hex)
  h <- HSV(c(0.25, 0.5, 0.75))
  expect_equal(h$to_hex(), o$hsv_hex)
  h$hue <- 0.6
  expect_equal(h$to_hex(), o$hsv_set_hex)
  expect_equal(h$h, 0.6)
  expect_equal((HSV(c(0.25, 0.5, 0.75)) + 0.1)$to_hex(), o$hsv_add)
  expect_equal(attr(c1$into(HSVClass), "hsva"), o$into_hsv)
  expect_identical(ManimColor("#FF8000") == ManimColor(c(1, 128 / 255, 0)), o$eq)
})

test_that("ManimColor works wherever a color is accepted", {
  c1 <- ManimColor(c(0.2, 0.4, 0.6))
  sq <- Square(color = c1)
  expect_equal(sq$get_color(), "#336699")
  expect_equal(color_to_rgba(c1), c(0.2, 0.4, 0.6, 1))
  expect_equal(interpolate_color(c1, WHITE, 0), "#336699")
  expect_equal(as.integer(ManimColor("#000102")), 258L)
  expect_output(print(c1), "ManimColor\\('#336699'\\)")
  expect_identical(RGBA, ManimColor)
  expect_length(ManimColorClass$parse(c(RED, BLUE)), 2)
  expect_length(ManimColorClass$gradient(list(RED, BLUE), 5), 5)
  expect_error(ManimColor("not a color"), "not found")
  expect_error(ManimColor(RED) == RED, "compare")
  expect_equal(!ManimColor(WHITE), ManimColor(BLACK))
  expect_equal(ManimColorDType, "double")
})

test_that("RandomColorGenerator repeats for a seed", {
  set.seed(1)
  before <- runif(1)
  set.seed(1)
  a <- RandomColorGenerator(42)
  b <- RandomColorGenerator(42)
  seq_a <- vapply(1:5, function(i) as.character(a$`next`()), "")
  seq_b <- vapply(1:5, function(i) as.character(b$next_color()), "")
  expect_identical(seq_a, seq_b)
  expect_equal(runif(1), before)
  g <- RandomColorGenerator(sample_colors = list(RED))
  expect_equal(as.character(g$next_color()), RED)
})
