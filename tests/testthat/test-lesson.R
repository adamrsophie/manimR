test_that("write_lesson() writes a movie, WebVTT chapters and captions, and a page", {
  skip_if_not(nzchar(Sys.which("ffmpeg")))
  skip_on_cran()
  out <- suppressMessages(render(function(self) {
    self$add_subcaption("A \"square\" & <b>", duration = 1)
    self$play(Create(Square()), run_time = 1)
    self$next_section("Circle")
    self$add_subcaption("Now a circle", duration = 1)
    self$play(Create(Circle()), run_time = 1)
  }, quality = "l", media_dir = withr_tempdir(), frame_rate = 10))
  dir <- file.path(withr_tempdir(), "lesson")
  expect_identical(write_lesson(out, dir, title = "Shapes & more"), dir)
  expect_setequal(list.files(dir), c("index.html", "chapters.vtt", "captions.vtt", basename(out)))
  chapters <- readLines(file.path(dir, "chapters.vtt"))
  expect_equal(chapters[1], "WEBVTT")
  expect_true(all(c("00:00:00.000 --> 00:00:01.000", "Start", "00:00:01.000 --> 00:00:02.000", "Circle") %in% chapters))
  captions <- readLines(file.path(dir, "captions.vtt"))
  expect_true("A \"square\" &amp; &lt;b&gt;" %in% captions)
  html <- paste(readLines(file.path(dir, "index.html")), collapse = "\n")
  expect_match(html, "<title>Shapes &amp; more</title>", fixed = TRUE)
  expect_match(html, 'data-t="1.050000">Circle', fixed = TRUE)
  expect_match(html, "new VTTCue", fixed = TRUE)
  expect_false(grepl("<b>", html, fixed = TRUE))
  expect_false(grepl("autoplay", html, fixed = TRUE))
  expect_false(grepl("https?://", html))
  expect_error(write_lesson("x.mp4", dir), "value of render")
})
